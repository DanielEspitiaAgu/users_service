CREATE TABLE match_saga_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(255) NOT NULL,
    source_event_id VARCHAR(255) NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    match_id VARCHAR(255) NOT NULL,
    correlation_id VARCHAR(255) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    claimed_until TIMESTAMP WITH TIME ZONE,
    claim_token UUID,
    last_error VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_match_saga_outbox_event UNIQUE (event_id),
    CONSTRAINT uq_match_saga_outbox_source UNIQUE (source_event_id),
    CONSTRAINT ck_match_saga_outbox_status CHECK (status IN ('PENDING', 'PUBLISHED')),
    CONSTRAINT ck_match_saga_outbox_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_match_saga_outbox_claim CHECK
        ((claimed_until IS NULL AND claim_token IS NULL) OR (claimed_until IS NOT NULL AND claim_token IS NOT NULL)),
    CONSTRAINT ck_match_saga_outbox_published CHECK
        ((status = 'PENDING' AND published_at IS NULL) OR (status = 'PUBLISHED' AND published_at IS NOT NULL))
);

CREATE INDEX ix_match_saga_outbox_pending
    ON match_saga_outbox (next_attempt_at, id)
    WHERE status = 'PENDING';
