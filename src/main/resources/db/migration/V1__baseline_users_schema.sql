CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username varchar(50),
    email varchar(100),
    external_id varchar(64) NOT NULL,
    name varchar(100),
    avatar varchar(255),
    language varchar(5) NOT NULL,
    tutorial_completed boolean NOT NULL,
    experience integer NOT NULL,
    streak integer NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_external_id UNIQUE (external_id)
);

CREATE TABLE achievements (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code varchar(50) NOT NULL,
    name varchar(100) NOT NULL,
    description varchar(255) NOT NULL,
    icon varchar(255),
    requirement varchar(50) NOT NULL,
    CONSTRAINT pk_achievements PRIMARY KEY (id),
    CONSTRAINT uq_achievements_code UNIQUE (code)
);

CREATE TABLE user_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    case_id varchar(255) NOT NULL,
    mode varchar(20) NOT NULL,
    won boolean NOT NULL,
    time_seconds integer NOT NULL,
    xp_delta integer NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT pk_user_results PRIMARY KEY (id),
    CONSTRAINT fk_user_results_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE user_achievements (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    achievement_id bigint NOT NULL,
    unlocked_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT pk_user_achievements PRIMARY KEY (id),
    CONSTRAINT uq_user_achievements_user_achievement UNIQUE (user_id, achievement_id),
    CONSTRAINT fk_user_achievements_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_achievements_achievement FOREIGN KEY (achievement_id) REFERENCES achievements (id)
);
